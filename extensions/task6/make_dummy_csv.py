#!/usr/bin/env python3
"""Create DUMMY result CSVs in the format of run_validation.m, to test compare.py end to end.

The numbers are the Python reference values multiplied by small random factors.  They are NOT
Simulink results; every file starts with '# DUMMY' and compare.py stamps all outputs DUMMY.
Output folder: DUMMY_simulink_out/
"""
import json, os
import numpy as np
import ref_models as R

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "DUMMY_simulink_out")
os.makedirs(OUT, exist_ok=True)
rng = np.random.default_rng(1)
ref = json.load(open(os.path.join(HERE, "python_reference.json")))
HDR = "# DUMMY DATA GENERATED BY make_dummy_csv.py (Python) - NOT SIMULINK RESULTS\n"


def rowsAB(set_):
    out = []
    cases = ref["caseA"] if set_ == "A" else ref["caseB"]
    models = ref["load_models_A"] if set_ == "A" else ref["load_models_B"]
    for c in cases:
        Sa, Sb = R.case_A_loads(c) if set_ == "A" else R.case_B_loads(c)
        for m in models:
            e = R.EXACT[m](Sa, Sb, c["Ssc_MVA"])
            vuf = e["VUF_pct"] * (1 + 0.004 * rng.standard_normal()) + abs(0.0005 * rng.standard_normal())
            iuf = e["IUF_pct"] + 0.05 * rng.standard_normal() * (e["IUF_pct"] > 0)
            iuf = abs(iuf)
            sa, sb = e["Sa_act_MVA"] * (1 + 0.002 * rng.standard_normal()), e["Sb_act_MVA"] * (1 + 0.002 * rng.standard_normal())
            d = dict(case_id=c["id"], load_model=m, Ssc_MVA=c["Ssc_MVA"])
            if set_ == "A":
                d.update(k=c["k"], dphi_deg=c["dphi_deg"])
            else:
                d.update(rating_MVA=c["rating_MVA"])
            if set_ == "A":
                a_, b_ = complex(c["Sa_MVA"] * np.cos(np.radians(c["phia_deg"])), c["Sa_MVA"] * np.sin(np.radians(c["phia_deg"]))), \
                         complex(c["Sb_MVA"] * np.cos(np.radians(c["phib_deg"])), c["Sb_MVA"] * np.sin(np.radians(c["phib_deg"])))
            else:
                a_, b_ = Sa, Sb
            d.update(Sa_set_P_MW=a_.real, Sa_set_Q_Mvar=a_.imag, Sb_set_P_MW=b_.real, Sb_set_Q_Mvar=b_.imag,
                     Sa_act_P_MW=sa.real, Sa_act_Q_Mvar=sa.imag, Sb_act_P_MW=sb.real, Sb_act_Q_Mvar=sb.imag,
                     IUF_pct=iuf, VUF_pct=vuf, V1_pcc_kVll=e["U1_pu"] * 110.0, VUF_seqblock_pct=np.nan, n_iter=4, converged=1)
            out.append(d)
    return out


def write(name, rows, cols):
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write(HDR)
        fh.write(",".join(cols) + "\n")
        for r in rows:
            fh.write(",".join(r[c] if isinstance(r[c], str) else f"{r[c]:.10g}" for c in cols) + "\n")


colsA = ["case_id", "load_model", "Ssc_MVA", "k", "dphi_deg"]
colsB = ["case_id", "load_model", "Ssc_MVA", "rating_MVA"]
tail = ["Sa_set_P_MW", "Sa_set_Q_Mvar", "Sb_set_P_MW", "Sb_set_Q_Mvar", "Sa_act_P_MW", "Sa_act_Q_Mvar", "Sb_act_P_MW",
        "Sb_act_Q_Mvar", "IUF_pct", "VUF_pct", "V1_pcc_kVll", "VUF_seqblock_pct", "n_iter", "converged"]
write("caseA_results.csv", rowsAB("A"), colsA + tail)
write("caseB_results.csv", rowsAB("B"), colsB + tail)

# case C: continuous-time Python solution with small perturbations
ser = dict(np.load(os.path.join(HERE, "python_caseC_series.npz")))
pyC = {(r["case_id"], r["method"]): r for r in ref["python_caseC"]}
sumrows, tsrows = [], []
for ff in (1, 0):
    cid = f"C_ff{ff}"
    co = pyC[(cid, "continuous_rk45")]
    for method, scale in (("simulink", 1.0004), ("matlab_ode45", 0.9998)):
        sumrows.append(dict(case_id=cid, method=method, ff=ff, Vdc_min_V=co["Vdc_min_V"] - 0.4,
                            Vdc_max_V=co["Vdc_max_V"] * scale, Vdc_dev_max_pct=co["Vdc_dev_max_pct"] * scale,
                            Ia_max_pu=co["Ia_max_pu"] * 1.001, Ib_max_pu=co["Ib_max_pu"] * 0.999,
                            settle_s=co["settle_s"] + (0.0005 if co["settle_s"] > 0 else 0.0), runtime_s=0.0))
        t = ser[f"cont_ff{ff}_t"]
        for i in range(0, len(t), 1):
            tsrows.append(dict(case_id=cid, method=method, t_s=t[i], Vdc_V=ser[f"cont_ff{ff}_Vdc"][i] * scale,
                               Ia_pu=ser[f"cont_ff{ff}_Ia"][i], Ib_pu=ser[f"cont_ff{ff}_Ib"][i],
                               Pa_MW=ser[f"cont_ff{ff}_Pa"][i], Pb_MW=ser[f"cont_ff{ff}_Pb"][i]))
write("caseC_summary.csv", sumrows, ["case_id", "method", "ff", "Vdc_min_V", "Vdc_max_V", "Vdc_dev_max_pct",
                                      "Ia_max_pu", "Ib_max_pu", "settle_s", "runtime_s"])
write("caseC_timeseries.csv", tsrows, ["case_id", "method", "t_s", "Vdc_V", "Ia_pu", "Ib_pu", "Pa_MW", "Pb_MW"])
print("dummy CSVs written to", OUT)
